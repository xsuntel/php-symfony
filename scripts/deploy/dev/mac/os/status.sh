# ----------------------------------------------------------------------------------------------------------------------
# Tools for VM ( Instance )
# ----------------------------------------------------------------------------------------------------------------------

setTools() {
  echo -e "----------------------------------------------------------------------------------------------------------"
  echo -e "[ ${ENVIRONMENT_NAME} ] ${PLATFORM_TYPE} - Tools for VM ( Instance )"
  echo -e "----------------------------------------------------------------------------------------------------------\n"

  # >>>> Environment
  if [ "${ENVIRONMENT_NAME}" == "dev" ]; then

    # >>>> Host
    scutil --get ComputerName
    echo

    hostname
    echo

    uname -n
    echo

    arp -a
    echo

    # >>>> Hardware
    networksetup -listallhardwareports
    echo

    route -n get default
    echo

    netstat -rn
    echo

    ifconfig
    echo

    grep -v '#' /etc/resolv.conf
    echo

    scutil --dns
    echo

    # >>>> Firewall
    sudo /usr/libexec/ApplicationFirewall/socketfilterfw --getglobalstate
    echo

    sudo pfctl -s info
    echo

    # >>>> status
    netstat -r
    echo

    netstat -an | grep LISTEN
    echo

    #netstat -p
    #echo

    netstat -i
    echo

    netstat -s
    echo

    sudo lsof -iTCP -sTCP:LISTEN -n -P
    echo

    # ------------------------------------------------------------------------------------------------------------------
    # Security - Logs
    # ------------------------------------------------------------------------------------------------------------------
    log show --predicate 'messageType == error' --last 1h --style compact
    echo

    fi
  echo
}


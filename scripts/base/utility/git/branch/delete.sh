setDocker() {
  echo -e "----------------------------------------------------------------------------------------------------------"
  echo -e "[ ${ENVIRONMENT_NAME} ] ${PLATFORM_TYPE} - Docker - Containers"
  echo -e "----------------------------------------------------------------------------------------------------------\n"

  # >>>> Docker - Images
  echo ">>>> Docker - images"
  echo

  docker system prune -a -f --filter "label=purpose=webapp"
  echo

  # >>>> Docker - Containers

  FILES_TO_DELETE=(
    "./app/Dockerfile"
    "./app/docker-compose.yml"
    "./Dockerfile"
    "./docker-compose.env"
    "./docker-compose.yml"
    "./docker-compose.${ENVIRONMENT_NAME}.env"
    "./docker-compose.${ENVIRONMENT_NAME}.yml"
    "./docker-compose.override.yml"
  )

  for file in "${FILES_TO_DELETE[@]}"; do
    if [ -f "$file" ]; then
      echo ">>>> Deleting: $file"
      rm -v "$file"
    fi
  done
  echo
}


find_project_root() {
    local PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    while [[ "${PROJECT_DIR}" != "/" ]]; do
        if [[ -d "${PROJECT_DIR}/.git" ]] || [[ -f "${PROJECT_DIR}/.env.app" ]]; then
            echo "${PROJECT_DIR}"
            return 0
        fi
        PROJECT_DIR="$(dirname "${PROJECT_DIR}")"
    done
    return 1
}

PROJECT_PATH=$(find_project_root)
PROJECT_NAME=$(basename "$(realpath "${PROJECT_PATH}")")
cd "${PROJECT_PATH}" || exit

# ----------------------------------------------------------------------------------------------------------------------
# Abstract
# ----------------------------------------------------------------------------------------------------------------------

if [ -f "${PROJECT_PATH}/scripts/base/_abstract.sh" ]; then
  source "${PROJECT_PATH}/scripts/base/_abstract.sh"
else
  echo "Please check a file : ./scripts/base/_abstract.sh" && exit
fi

# >>>> Environment

setEnvironment() {
  echo -e "----------------------------------------------------------------------------------------------------------"
  echo -e "[ ENV ] ${PLATFORM_TYPE} - ${PLATFORM_PROCESSOR}"
  echo -e "----------------------------------------------------------------------------------------------------------\n"
  PS3="Menu: "
  select num in "dev" "exit"; do
    case "$REPLY" in
    1)
      # >>>> Dev Environment
      ENVIRONMENT_NAME="dev"
      break
      ;;
    2)
      echo "exit()"
      setEnd
      ;;
    *)
      echo "[ ERROR ] Unknown Command"
      setEnd
      ;;
    esac
  done

  echo
  echo "- PROJECT ENV : ${ENVIRONMENT_NAME}"
  echo
}

# >>>> Platform

setPlatform() {
  echo "---------------------------------------------------------------------------------------------------------------"
  echo "[ ${ENVIRONMENT_NAME} ] ${PLATFORM_TYPE} - Platform "
  echo "---------------------------------------------------------------------------------------------------------------"
  echo

  # >>>> Environment
  if [ "${ENVIRONMENT_NAME}" == "dev" ]; then

    # >>>> Platform
    if [ "${PLATFORM_TYPE}" == "Linux" ]; then
      # ------------------------------------------------------------------------------------------------------------------
      # Platform - Linux - Ubuntu
      # ------------------------------------------------------------------------------------------------------------------

      # >>>> User
      echo ">>>> Linux - Users"
      echo

      if [ -f "/etc/sudoers.d/${USER}" ]; then
        sudo rm -fv "/etc/sudoers.d/${USER}"
      fi

      # >>>> Files
      if [ -d ~/.local/share/Trash ]; then
        rm -rf ~/.local/share/Trash/*
      fi

    elif [ "${PLATFORM_TYPE}" == "Darwin" ]; then
      # ------------------------------------------------------------------------------------------------------------------
      # Platform - Mac - MacOS
      # ------------------------------------------------------------------------------------------------------------------

      # >>>> Files
      echo


    elif [ "${PLATFORM_TYPE}" == "Windows" ]; then
      # ------------------------------------------------------------------------------------------------------------------
      # Platform - Windows - WSL2
      # ------------------------------------------------------------------------------------------------------------------

      # >>>> Files
      echo

    else
      echo "Please check Operating System"
      setExit
    fi

  fi
}

# >>>> Project

setProject() {
  echo -e "----------------------------------------------------------------------------------------------------------"
  echo -e "[ ${ENVIRONMENT_NAME} ] ${PLATFORM_TYPE} - Project : ${PROJECT_NAME}"
  echo -e "----------------------------------------------------------------------------------------------------------\n"

  # >>>> Directory
  if [ -f "${PROJECT_PATH}/scripts/base/_project.sh" ]; then
    source "${PROJECT_PATH}/scripts/base/_project.sh"
  else
    echo "Please check a file : ./scripts/base/_project.sh" && exit
  fi
}

# ----------------------------------------------------------------------------------------------------------------------
# Architecture
# ----------------------------------------------------------------------------------------------------------------------

# >>>> App

setPhp() {
  echo -e "----------------------------------------------------------------------------------------------------------"
  echo -e "[ ${ENVIRONMENT_NAME} ] ${PLATFORM_TYPE} - Base - App - Packages"
  echo -e "----------------------------------------------------------------------------------------------------------\n"

  # >>>> Project - App
  if [ -d app ]; then
    (
      cd app || return

      # >>>> PHP - Symfony Command                                        https://symfony.com/doc/current/deployment.html
      if [ -f bin/console ]; then

        # >>>> Environment
        if [ "${ENVIRONMENT_NAME}" == "dev" ]; then

          echo ">>>> App - PHP - Symfony - Messenger"
          echo

          symfony console messenger:stop-workers
          echo

          echo ">>>> App - PHP - Symfony - Local Server"
          echo
          symfony local:server:stop
          echo

        fi

      fi
    )
  else
    echo
    echo "[ ERROR ] There is not a folder : app"
    echo
    setExit
  fi

  # >>>> Environment
  if [ "${ENVIRONMENT_NAME}" == "dev" ]; then

    # >>>> Platform
    if [ "${PLATFORM_TYPE}" == "Linux" ]; then
      echo ">>>> Linux - Delete a directory : ./app"
      echo

      if [ -f app/bin/console ]; then
        rm -rf app
        mkdir app
        touch app/.gitkeep
      fi

    elif [ "${PLATFORM_TYPE}" == "Darwin" ]; then
      echo ">>>> Mac - Delete a directory : ./app"
      echo

      if [ -f app/bin/console ]; then
        rm -rf app
        mkdir app
        touch app/.gitkeep
      fi

    elif [ "${PLATFORM_TYPE}" == "Windows" ]; then
      echo ">>>> Windows - Delete a directory : ./app"
      echo

      if [ -f app/bin/console ]; then
        rm -rf app
        mkdir app
        touch app/.gitkeep
      fi

    else
      echo "Please check Operating System"
      setExit
    fi
  fi
  echo
}

